import Foundation

enum AppLanguage: String, CaseIterable, Identifiable {
    case spanish = "es"
    case english = "en"

    static let preferenceKey = "domoHomeLanguage"

    static var current: AppLanguage {
        AppLanguage(rawValue: UserDefaults.standard.string(forKey: preferenceKey) ?? "es") ?? .spanish
    }

    var id: String { rawValue }

    var displayName: String {
        switch self {
        case .spanish: "Español"
        case .english: "English"
        }
    }
}

