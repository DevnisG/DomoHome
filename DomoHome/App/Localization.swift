    static func text(_ value: String) -> String {
        guard AppLanguage.current == .english else { return value }
        return english[value] ?? value
    }

    static func format(_ value: String, _ arguments: CVarArg...) -> String {
        String(format: text(value), locale: Locale(identifier: AppLanguage.current.rawValue), arguments: arguments)
    }
